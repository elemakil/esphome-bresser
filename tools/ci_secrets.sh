#!/usr/bin/env bash
# Write a throwaway secrets.yaml so CI can compile. NOT for humans -- copy
# secrets.yaml.example and fill it in instead.
#
# Why this exists: secrets.yaml.example cannot be used verbatim. Its api_encryption_key
# placeholder reads "generate-your-own", and ESPHome's api component validates that the key
# is 32 base64-encoded bytes, so `esphome config` rejects it before reaching anything worth
# checking.
#
# The key is generated fresh on every run and never committed. A valid-looking key baked
# into secrets.yaml.example would be a publicly known key that someone could ship to a real
# device by accident. A random one that lives for the length of a CI job cannot be.
#
# Nothing built from these values may ever be flashed: wrong Wi-Fi credentials take the
# device off the network.
#
# Keep the keys in step with secrets.yaml.example: an example that references a secret this
# file does not write fails CI with "Secret '...' not defined".
set -euo pipefail

dir="${1:-}"
[ -n "$dir" ] && [ -d "$dir" ] || {
    echo "usage: tools/ci_secrets.sh <config-dir>" >&2
    exit 2
}

if [ -z "${CI:-}" ] && [ -z "${FORCE_CI_SECRETS:-}" ]; then
    echo "error: refusing to run outside CI -- this would overwrite $dir/secrets.yaml" >&2
    echo "       with placeholder values. Set FORCE_CI_SECRETS=1 if that is really what" >&2
    echo "       you want (it is not, if the device is on your network)." >&2
    exit 2
fi

key="$(python3 -c 'import base64, secrets; print(base64.b64encode(secrets.token_bytes(32)).decode())')"

cat >"$dir/secrets.yaml" <<EOF
# Generated by tools/ci_secrets.sh. Throwaway values for a CI build only.
wifi_ssid: "ci-build-only"
wifi_password: "ci-build-only-not-a-real-password"
ap_password: "ci-build-only"
api_encryption_key: "$key"
ota_password: "ci-build-only"
EOF

echo "wrote $dir/secrets.yaml (throwaway; api key generated fresh)"
